CREATE DATABASE SCHOOL_MAX
GO
USE SCHOOL_MAX
GO
SELECT DB_NAME()AS BaseActual;

CREATE TABLE ROL(
    ID_ROL INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL
);

CREATE TABLE USUARIO(
    ID_Usuario INT IDENTITY(1,1) PRIMARY KEY,
    Numero_Documento VARCHAR (25) NOT NULL,
    Contraseña VARCHAR(50) NOT NULL,
    Tipo_Documento VARCHAR(10) NOT NULL,
    Nombres VARCHAR(50) NOT NULL,
    Apellidos VARCHAR(50) NOT NULL,
    Correo VARCHAR(100) NOT NULL,
    Numero_Celular VARCHAR (25) NOT NULL,
    ID_Rol INT NOT NULL,
    FOREIGN KEY (ID_Rol) REFERENCES ROL(ID_Rol)
);

CREATE TABLE SALON(
    ID_Salon INT IDENTITY(1,1) PRIMARY KEY,
    Nombre_Salon VARCHAR(50),
    Cupos INT
);

CREATE TABLE CURSO(
    ID_Curso INT IDENTITY(1,1) PRIMARY KEY,
    Nombre VARCHAR(20) NOT NULL,
    ID_Salon INT NOT NULL,
    FOREIGN KEY (ID_Salon) REFERENCES Salon(ID_Salon)
);

CREATE TABLE ASIGNATURA(
    ID_Asignatura INT IDENTITY(1,1) PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL
);

CREATE TABLE ESTADO(
	ID_Estado INT IDENTITY (1,1) PRIMARY KEY,
	Nombre VARCHAR (15) NOT NULL
);

CREATE TABLE MATRICULA(
	ID_Matricula INT IDENTITY(1,1) PRIMARY KEY,
	Numero_Radicado VARCHAR (45),
	Fecha DATE NOT NULL,
	ID_Curso INT NOT NULL,
	ID_Estado INT NOT NULL,

	FOREIGN KEY (ID_Curso) REFERENCES CURSO(ID_Curso),
	FOREIGN KEY (ID_Estado) REFERENCES ESTADO(ID_Estado)
);

CREATE TABLE ESTUDIANTE(
	 ID_Estudiante INT IDENTITY(1,1) PRIMARY KEY,
	 Numero_Documento VARCHAR (25) NOT NULL,
	 Fecha_Nacimiento DATE NOT NULL,
	 Nombre VARCHAR (30) NOT NULL,
	 Apellidos VARCHAR (30) NOT NULL,
	 Numero_Celular VARCHAR (25),
	 Direccion VARCHAR (50) NOT NULL,
	 ID_Estado INT NOT NULL,
	 ID_Matricula INT NOT NULL,

	 FOREIGN KEY (ID_Estado) REFERENCES ESTADO(ID_Estado),
	 FOREIGN KEY (ID_Matricula) REFERENCES MATRICULA(ID_Matricula)
);

CREATE TABLE DOCENTE_CURSO_ASIGNATURA(
    ID_DOCENTE_CURSO_ASIGNATURA INT IDENTITY(1,1) PRIMARY KEY,
    ID_Asignatura INT NOT NULL,
    ID_Curso INT NOT NULL,
    ID_Docente INT NOT NULL,
    FOREIGN KEY (ID_Asignatura) REFERENCES ASIGNATURA(ID_Asignatura),
    FOREIGN KEY (ID_Curso) REFERENCES CURSO(ID_Curso),
    FOREIGN KEY (ID_Docente) REFERENCES USUARIO(ID_Usuario)
);

CREATE TABLE PERIODO_ACADEMICO(
	ID_Periodo_Academico INT IDENTITY (1,1) PRIMARY KEY,
	Nombre VARCHAR (20) NOT NULL,
	Fecha_Inicio DATE NOT NULL,
	Fecha_Fin DATE NOT NULL
);

CREATE TABLE ESTUDIANTE_ASIGNATURA_NOTA(
	 ID_Estudiante_Asignatura_Nota INT IDENTITY(1,1) PRIMARY KEY,
	 Nota_1 FLOAT,
	 Nota_2 FLOAT,
	 Nota_3 FLOAT,
	 ID_Estudiante INT NOT NULL,
	 ID_Asignatura INT NOT NULL,
	 ID_Periodo_Academico INT NOT NULL,

	 FOREIGN KEY (ID_Estudiante) REFERENCES ESTUDIANTE(ID_Estudiante),
	 FOREIGN KEY (ID_Asignatura) REFERENCES ASIGNATURA(ID_Asignatura),
	 FOREIGN KEY (ID_Periodo_Academico) REFERENCES PERIODO_ACADEMICO(ID_Periodo_Academico)
);

CREATE TABLE PARENTESCO(
	ID_Parentesco INT IDENTITY (1,1) PRIMARY KEY,
	NOMBRE VARCHAR (15) NOT NULL
);

CREATE TABLE ESTUDIANTE_ACUDIENTE(
	ID_Estudiante_Acudiente INT IDENTITY(1,1) PRIMARY KEY,
	ID_Estudiante INT NOT NULL,
	ID_Acudiente INT NOT NULL,
	ID_Parentesco INT NOT NULL,

	FOREIGN KEY (ID_Estudiante) REFERENCES ESTUDIANTE(ID_Estudiante),
	FOREIGN KEY (ID_Acudiente) REFERENCES USUARIO(ID_Usuario),
	FOREIGN KEY (ID_Parentesco) REFERENCES PARENTESCO(ID_Parentesco)
);

CREATE TABLE TIPO_REPORTE(
	ID_Tipo_Reporte INT IDENTITY (1,1) PRIMARY KEY,
	Nombre VARCHAR (30)
);

CREATE TABLE REPORTE(
	ID_Reporte INT IDENTITY (1,1) PRIMARY KEY,
	ID_Tipo_Reporte INT NOT NULL,
	ID_Estudiante INT NOT NULL,
	Descripcion NVARCHAR (255) NOT NULL,
	Fecha_Generacion DATE NOT NULL,

	CONSTRAINT ID_Tipo_Reporte FOREIGN KEY (ID_Tipo_Reporte) REFERENCES TIPO_REPORTE(ID_Tipo_Reporte),
	CONSTRAINT ID_Estudiante FOREIGN KEY (ID_Estudiante) REFERENCES ESTUDIANTE(ID_Estudiante)
);